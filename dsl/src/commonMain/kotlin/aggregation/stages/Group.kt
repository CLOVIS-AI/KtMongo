	 * **This function can only be called on the `_id` field or one of its subfields.**
	 *
	 * ### Simple example
	 *
	 * We can compute the average age of users in the different cities we have users in:
	 *
	 * ```kotlin
	 * class User(
	 *     val _id: ObjectId,
	 *     val name: String,
	 *     val age: Int,
