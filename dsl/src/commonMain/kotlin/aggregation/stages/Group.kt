	 * )
	 *
	 * class AgePerCity(
	 *     val _id: String,
	 *     val averageAge: Double,
	 * )
	 *
	 * users.aggregate()
	 *     .group {
	 *         // Group by city name
	 *         AgePerCity::_id set User::city
	 *
