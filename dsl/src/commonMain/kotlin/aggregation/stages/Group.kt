@OptIn(LowLevelApi::class)
private class GroupStageOperatorsImpl<From : Any, Into : Any>(
	context: BsonContext,
) : AbstractCompoundBsonNode(context), GroupStageOperators<From, Into> {

	override fun write(writer: BsonFieldWriter, children: List<BsonNode>) = with(writer) {
		val idMappings = children.filterIsInstance<IdMappingNode>()
		val others = children.filter { it !is IdMappingNode }

		when {
			idMappings.isEmpty() -> writeNull("_id")

			idMappings.size == 1 && idMappings.first().path.parent == null ->
				write("_id") { idMappings.first().value.writeTo(this) }

			else -> writeDocument("_id") {
				writeIdChildren(idMappings.map { it.path.asSequence().drop(1).toList() to it.value })
			}
		}

		super.write(this, others)
	}

	private fun BsonFieldWriter.writeIdChildren(entries: List<Pair<List<PathSegment>, Value<*, *>>>) {
		val bySegment = LinkedHashMap<PathSegment, MutableList<Pair<List<PathSegment>, Value<*, *>>>>()
		for ((segments, value) in entries) {
			bySegment.getOrPut(segments.first()) { mutableListOf() } += segments.drop(1) to value
		}

		for ((segment, rest) in bySegment) {
			val single = rest.singleOrNull()
			if (single != null && single.first.isEmpty()) {
				write(segment.toString()) { single.second.writeTo(this) }
			} else {
				writeDocument(segment.toString()) { writeIdChildren(rest) }
			}
		}
	}

	@OptIn(DangerousMongoApi::class)
	override fun <V> Field<Into, V>.set(value: Value<From, V>) {
		val path = this.path
		require((path.asSequence().firstOrNull() as? PathSegment.Field)?.name == "_id") { $$"Inside a $group stage, the only field that can be set is _id (and its children), but this stage attempted to set the field $$path" }
		accept(IdMappingNode(path, value, context))
	}
}

private class GroupStage(
	val operators: GroupStageOperatorsImpl<*, *>,
	context: BsonContext,
) : AbstractBsonNode(context) {

	@LowLevelApi
	override fun write(writer: BsonFieldWriter) = with(writer) {
		writeDocument("\$group") {
			operators.writeTo(this)
		}
	}
}

@LowLevelApi
private class IdMappingNode(
	val path: Path,
	val value: Value<*, *>,
	context: BsonContext,
) : AbstractBsonNode(context) {

	override fun write(writer: BsonFieldWriter) = with(writer) {
		write(path.toString()) {
			value.writeTo(this)
		}
	}
}
